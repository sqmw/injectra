"""Private extension ports. Test doubles do not register product support."""
from typing import Any, Protocol
from session_model import TargetIdentity

class TargetProvider(Protocol):
    def bind(self, target: TargetIdentity) -> TargetIdentity: ...
    def verify_attached(self, session: Any, target: TargetIdentity) -> None: ...
    def verify_agent(self, target: TargetIdentity, receipt: dict) -> None: ...

class AttachedTransport(Protocol):
    session: Any
    def close(self) -> None: ...

class TransportConnector(Protocol):
    def attach(self, target: TargetIdentity) -> AttachedTransport: ...
