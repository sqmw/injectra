"""Observe real host sendEvent: calls in an explicitly owned macOS app instance."""
import argparse
import json
import math
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tests/frida"))
from gadget_probe import run_owned, deadline


def validate_observation(observed, restored, after):
    if observed["calls"] < 1 or not observed["installed"] or observed["restored"]:
        raise RuntimeError("No completed natural host calls; synthetic calls are not a substitute")
    for receipt in (observed, restored, after):
        if (receipt["wrongReceiver"] or receipt["wrongThread"] or receipt["inFlight"]
                or receipt["completed"] != receipt["calls"]
                or not receipt["running"] or not receipt["mainThread"]):
            raise RuntimeError("Receiver, original call completion, or host health mismatch")
    if (not restored["restored"] or restored["installed"] or not after["restored"]
            or after["installed"] or after["calls"] != restored["calls"]
            or after["completed"] != restored["completed"]
            or restored["calls"] < observed["calls"]):
        raise RuntimeError("Restoration or callback quiescence failed")


def exercise(script, result, timeout, observe):
    result["observationSeconds"] = observe
    result["stage"] = "host-ready"
    end = time.monotonic() + timeout
    while True:
        with deadline(timeout):
            installed = script.exports_sync.install()
        if installed["ready"]:
            break
        if time.monotonic() >= end:
            raise TimeoutError("Actual host not ready")
        time.sleep(.1)
    result["installation"] = installed
    print(json.dumps({"stage": "observing-natural-calls", "class": installed["actualClass"],
                      "owner": installed["declaringClass"], "module": installed["originalModule"]}), flush=True)
    result["stage"] = "natural-calls"
    time.sleep(observe)  # No sendEvent: call or synthetic event is generated by this fixture.
    with deadline(timeout):
        result["observed"] = script.exports_sync.snapshot()
    result["stage"] = "restore"
    with deadline(timeout):
        result["restored"] = script.exports_sync.restore()
    time.sleep(1)
    with deadline(timeout):
        result["afterRestore"] = script.exports_sync.snapshot()
    validate_observation(result["observed"], result["restored"], result["afterRestore"])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--app", type=Path, required=True)
    parser.add_argument("--gadget", type=Path, required=True)
    parser.add_argument("--deadline", type=float, default=20)
    parser.add_argument("--observe", type=float, default=30, help="Passive observation seconds; 1 for quick tests")
    args = parser.parse_args()
    if not math.isfinite(args.observe) or not 0 < args.observe <= 30:
        parser.error("observe must be between 0 and 30 seconds")
    return run_owned(args, agent_path=ROOT / "tests/frida/host-dispatch-hook.js",
                     route="gadget-required-host-dispatch", prefix="douyin-host-hook-",
                     exercise=lambda script, result, timeout: exercise(script, result, timeout, args.observe))


if __name__ == "__main__":
    raise SystemExit(main())
